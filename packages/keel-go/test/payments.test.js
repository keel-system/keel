// Los cobros con pasarela (incremento 13b), sin Go: lo que no puede cambiar con la pasarela (las piezas neutras), lo que
// tiene que decir lo mismo que keel-nest y keel-spring (payments.yaml, la ruta del aviso abierta, la tabla de monedas y los
// rechazos de keel-core) y lo que no se ve sin leer (el despacho sin transacción, lo que recibe cada handler y que lo que
// decide el agente vive fuera de un archivo de código generado). El adaptador y el verificador los EJECUTAN sus pruebas
// emitidas (`<pasarela>_test.go`) en `npm run go-check`, contra una pasarela falsa con las formas del doble.

import test from 'node:test';
import assert from 'node:assert/strict';
import path from 'node:path';
import { loadService } from '@keel-system/keel-core';
import { CURRENCY_MINOR_UNITS, PAYMENT_NOTICE_PATH, gatewayTranslation } from '@keel-system/keel-core/gen/payment-gateways';
import { planService as planNest } from '../../keel-nest/src/scaffold/index.js';
import { planService } from '../src/scaffold/index.js';
import { checkGoTree } from './helpers/go-tree.js';
import { checkGoIdioms } from './helpers/go-idioms.js';
import { FIXTURES_DIR } from './helpers/workspace.js';

const SUBJECT = 'payment-checkout';
const GATEWAYS = ['stripe', 'mercadopago'];
const STACK = { database: 'postgresql', broker: 'rabbitmq', auth: 'keycloak' };
const GENERATED = '// Code generated by keel-go. DO NOT EDIT.';

const plan = (gateway, planner = planService) =>
  planner({ ...loadService(path.join(FIXTURES_DIR, SUBJECT)), workspace: FIXTURES_DIR, stack: { ...STACK, paymentGateway: gateway } });
const content = (files, suffix) => files.find((file) => file.path.endsWith(suffix))?.content;
const PAYMENT_DIR = 'internal/infrastructure/payment/';

test('payments.yaml es el de keel-nest byte a byte, en los cuatro perfiles y con las dos pasarelas', () => {
  for (const gateway of GATEWAYS) {
    const go = plan(gateway).files;
    const nest = plan(gateway, planNest).files;
    for (const profile of ['local', 'develop', 'production', 'test']) {
      const file = `config/parameters/${profile}/payments.yaml`;
      assert.ok(content(go, file), `${gateway}: falta ${file}`);
      assert.equal(content(go, file), content(nest, file), `${gateway}: ${file}`);
    }
  }
});

test('entre pasarelas solo cambian su adaptador, sus pruebas y la configuración fuera de local y test', () => {
  const [stripe, mercadopago] = GATEWAYS.map((gateway) => new Map(plan(gateway).files.map((file) => [file.path, file.content])));
  const differing = [...new Set([...stripe.keys(), ...mercadopago.keys()])].filter((file) => stripe.get(file) !== mercadopago.get(file)).sort();
  const allowed = [
    /^internal\/infrastructure\/payment\/(stripe|mercadopago)(_test)?\.go$/,
    // El nombre de la pasarela en el comentario del paquete.
    /^internal\/infrastructure\/payment\/doc\.go$/,
    /^config\/parameters\/(develop|production)\/payments\.yaml$/,
    // La pasarela de prueba del arnés: las formas del doble son las de la pasarela; su API, la misma (abajo).
    /^tests\/integration\/payment_gateway_test\.go$/,
    // Lo que no es Go: las skills, el README y lo que cita la pasarela del stack.
    /\.(md|json|yaml|yml|sh|env)$/
  ];
  for (const file of differing) assert.ok(allowed.some((pattern) => pattern.test(file)), `${file} cambia con la pasarela`);
  // El puerto, el aplicador y la ruta del aviso: idénticos.
  for (const file of ['internal/domain/payment_gateway.go', 'internal/application/payment_outcomes.go', 'internal/httpapi/payment_notice.go', `${PAYMENT_DIR}http.go`, `${PAYMENT_DIR}money.go`]) {
    assert.ok(stripe.has(file), file);
    assert.equal(stripe.get(file), mercadopago.get(file), file);
  }
  // Los escenarios no nombran la pasarela: el arnés ofrece los mismos métodos, tipos y constantes con las dos.
  const api = (text) => text.split('\n').filter((line) => /^(func (\(s \*Scenario\) )?[A-Z]|type [A-Z]|\tCall\w+ +GatewayCall = )/.test(line));
  const harness = 'tests/integration/payment_gateway_test.go';
  assert.ok(api(stripe.get(harness)).length >= 20);
  assert.deepEqual(api(stripe.get(harness)), api(mercadopago.get(harness)));
});

test('la configuración lee solo claves que payments.yaml declara, y lo obligatorio no tiene default', () => {
  const { files } = plan('stripe');
  const settings = content(files, `${PAYMENT_DIR}settings.go`);
  const read = [...settings.matchAll(/"(payments\.[a-z.-]+)"/g)].map((match) => match[1]);
  const yaml = content(files, 'config/parameters/production/payments.yaml');
  const declared = new Set();
  const stack = [];
  for (const line of yaml.split('\n')) {
    const match = /^( *)([a-z-]+):/.exec(line);
    if (!match) continue;
    const depth = match[1].length / 2;
    stack.length = depth;
    stack.push(match[2]);
    declared.add(stack.join('.'));
  }
  assert.ok(read.length >= 8, read.join(', '));
  for (const key of read) assert.ok(declared.has(key), `settings.go lee ${key}, que payments.yaml no declara`);
  for (const key of ['payments.gateway.base-url', 'payments.gateway.api-key', 'payments.gateway.webhook-secret']) {
    assert.match(settings, new RegExp(`required\\("${key.replaceAll('.', '\\.')}"\\)`), key);
  }
});

test('la tabla de monedas es la de keel-core, entera, y nunca redondea', () => {
  const money = content(plan('stripe').files, `${PAYMENT_DIR}money.go`);
  for (const [code, digits] of Object.entries(CURRENCY_MINOR_UNITS)) assert.ok(money.includes(`"${code}": ${digits},`), code);
  assert.match(money, /scaled\.Cmp\(amount\) != 0/, 'el importe que habría que redondear es un error (Cmp, no Equal: 12.5 y 12.50 valen lo mismo)');
});

test('los rechazos de cada pasarela son los de keel-core, y la clave sale de la referencia', () => {
  for (const gateway of GATEWAYS) {
    const { files } = plan(gateway);
    const adapter = content(files, `${PAYMENT_DIR}${gateway}.go`);
    for (const [code] of gatewayTranslation(gateway).declines) assert.ok(adapter.includes(`"${code}":`), `${gateway}: ${code}`);
    const keys = content(files, `${PAYMENT_DIR}keys.go`);
    assert.match(keys, /return reference \+ ":" \+ action\n/);
    assert.match(keys, /return "save:" \+ token \+ ":" \+ step\n/);
    // Ningún aleatorio en la clave.
    assert.doesNotMatch(adapter + keys, /crypto\/rand|uuid\.New/);
  }
});

test('el cliente de la pasarela no reintenta ni reutiliza conexiones', () => {
  const http = content(plan('stripe').files, `${PAYMENT_DIR}http.go`);
  assert.match(http, /DisableKeepAlives: +true/);
  assert.match(http, /http\.ErrUseLastResponse/);
  assert.doesNotMatch(http, /for .*attempt|retry/i);
});

test('lo que llama a la pasarela se despacha SIN transacción: los endpoints y el barrido', () => {
  const { model, files } = plan('stripe');
  const endpoints = files.filter((file) => file.path.startsWith('internal/httpapi/') && !file.path.endsWith('_test.go')).map((file) => file.content).join('\n');
  const p = model.payments;
  for (const operation of [p.charge.operation, p.capture.operation, p.void.operation, p.refund.operation, p.savePaymentMethod.operation]) {
    const field = operation[0].toUpperCase() + operation.slice(1);
    assert.match(endpoints, new RegExp(`a\\.useCases\\.${field}\\.Handle\\(application\\.WithoutTransaction\\(r\\.Context\\(\\)\\)`), operation);
  }
  const scheduler = files.filter((file) => file.path.startsWith('internal/infrastructure/scheduler/')).map((file) => file.content).join('\n');
  assert.match(scheduler, /uc\.SweepPendingPayments\.Handle\(application\.WithoutTransaction\(ctx\)/);
  // El aplicador devuelve la transacción a cada desenlace.
  assert.match(content(files, 'internal/application/payment_outcomes.go'), /ctx = context\.WithValue\(ctx, withoutTransactionKey\{\}, false\)/);
});

test('cada handler de la capa recibe lo que necesita de la pasarela, y el arranque lo cablea', () => {
  const { model, files } = plan('stripe');
  const p = model.payments;
  const operations = new Map(model.services.flatMap((service) => service.operations).map((operation) => [operation.name, operation]));
  const snake = (name) => name.replace(/[A-Z]/g, (c) => `_${c.toLowerCase()}`);
  const handler = (operation) => content(files, `internal/application/${snake(operations.get(operation).messageClass)}_handler.go`.replace('/_', '/'));
  for (const operation of [p.charge.operation, p.capture.operation, p.void.operation, p.refund.operation]) {
    assert.match(handler(operation), /\tpaymentGateway domain\.PaymentGateway\n/, operation);
    assert.match(handler(operation), /\tpaymentOutcomes \*PaymentOutcomeApplier\n/, operation);
  }
  assert.match(handler(p.savePaymentMethod.operation), /\tpaymentGateway domain\.PaymentGateway\n/);
  assert.doesNotMatch(handler(p.savePaymentMethod.operation), /paymentOutcomes/);
  assert.match(handler(p.reconciliation.sweep), /\tpaymentReconciliation \*PaymentReconciliation\n/);
  const useCases = content(files, 'internal/application/use_cases.go');
  assert.match(useCases, /\tPaymentNotices \*PaymentNotices\n/);
  assert.match(useCases, /uc\.PaymentNotices = &PaymentNotices\{gateway: deps\.PaymentGateway, verifier: deps\.PaymentNoticeVerifier, outcomes: paymentOutcomes\}/);
  const main = content(files, 'cmd/server/main.go');
  assert.match(main, /paymentSettings, err := payment\.SettingsFrom\(cfg\)/);
  assert.match(main, /PaymentGateway: +payment\.NewGateway\(paymentSettings\),/);
  assert.match(main, /PaymentNoticeVerifier: +payment\.NewNoticeVerifier\(paymentSettings\),/);
});

test('la ruta del aviso existe, lee el cuerpo como texto y la abre la seguridad', () => {
  const { files } = plan('stripe');
  const notice = content(files, 'internal/httpapi/payment_notice.go');
  assert.ok(notice.includes(`const paymentNoticePath = "${PAYMENT_NOTICE_PATH}"`));
  assert.match(notice, /io\.ReadAll\(r\.Body\)/);
  assert.match(notice, /w\.WriteHeader\(http\.StatusUnauthorized\)/);
  const httpapi = files.filter((file) => file.path.startsWith('internal/httpapi/')).map((file) => file.content).join('\n');
  assert.match(httpapi, /mux\.Handle\(http\.MethodPost\+" "\+paymentNoticePath, a\.endpoint\(\(\*api\)\.receivePaymentNotice\)\)/);
  assert.ok(httpapi.includes(`"${PAYMENT_NOTICE_PATH}"`), 'la regla del plan de acceso que abre el aviso');
});

test('lo que la capa no nombra lo decide el agente en un archivo sin la cabecera; el aplicador generado no lleva TODO', () => {
  const { files } = plan('stripe');
  const applier = content(files, 'internal/application/payment_outcomes.go');
  assert.ok(applier.startsWith(GENERATED));
  assert.doesNotMatch(applier, /TODO/);
  assert.match(applier, /cancelReason, err := a\.markCanceledCancelReason\(ctx, outcome\)/);
  assert.match(applier, /\tpaymentRepository domain\.PaymentRepository\n/);
  const choices = content(files, 'internal/application/payment_outcome_choices.go');
  assert.ok(!choices.startsWith(GENERATED), 'payment_outcome_choices.go es del agente');
  assert.match(choices, /func \(a \*PaymentOutcomeApplier\) markCanceledCancelReason\(ctx context\.Context, outcome domain\.GatewayOutcome\) \(domain\.CancelReason, error\)/);
  for (const file of files.filter((candidate) => candidate.path.startsWith(PAYMENT_DIR) || candidate.path.endsWith('payment_gateway.go'))) {
    assert.doesNotMatch(file.content, /TODO/, file.path);
  }
});

