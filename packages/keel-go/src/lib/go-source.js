// Escribir un archivo Go que `gofmt -l` deje en paz y que compile, sin tener Go instalado.
//
// Es la pieza que los otros tres generadores no necesitaron (PLAN-KEEL-GO.md § 4): en Go un import sin usar
// es un error de compilación, y el formato no es una preferencia sino el de gofmt, byte a byte. Lleva tres
// cosas:
//   · el COLECTOR de imports: el emisor ofrece los que puede necesitar y aquí se quedan los que el cuerpo usa
//     de verdad, en los tres grupos de goimports (biblioteca estándar, terceros, el propio módulo);
//   · la ALINEACIÓN de gofmt para lo que un emisor genera por filas (campos de un struct, un bloque const,
//     un literal clave-valor), con la heurística de go/printer para los literales;
//   · la CABECERA de código generado: lo que escribe build y el agente no debe tocar la lleva
//     (`// Code generated by keel-go. DO NOT EDIT.`, que reconocen gopls y los linters); lo que completa el
//     agente no.
//
// Lo comprueba `go-check` con el gofmt real sobre todo lo emitido, y `test/go-source.test.js` contra salidas
// de gofmt capturadas.

/** La cabecera estándar de código generado (https://go.dev/s/generatedcode). */
export const GENERATED_HEADER = '// Code generated by keel-go. DO NOT EDIT.';

/** ¿Es de la biblioteca estándar? Su primer elemento no lleva punto (`net/http`, `encoding/json`). */
export function isStdlib(importPath) {
  return !importPath.split('/')[0].includes('.');
}

/**
 * El nombre con el que se usa un paquete importado: el último elemento de su ruta, salvo el sufijo de
 * versión mayor (`go.yaml.in/yaml/v3` → `yaml`) y los guiones o puntos (`go-cmp/cmp` → `cmp`).
 */
export function packageNameOf(importPath) {
  const parts = importPath.split('/');
  let last = parts.at(-1);
  if (/^v[0-9]+$/.test(last) && parts.length > 1) last = parts.at(-2);
  return last.replace(/^go-/, '').replace(/[.-].*$/, '');
}

/**
 * Un archivo Go entero. `imports` son rutas (o `{ path, name }` con alias); las del propio módulo pueden ir
 * relativas (`internal/platform/config`) y se completan con `module`. Solo se escriben las que el cuerpo usa:
 * un import sin usar no compila.
 */
export function goFile({ pkg, doc = null, imports = [], body, module = null, generated = true, build = null }) {
  const used = collectImports(imports, body, module);
  const parts = [];
  if (generated) parts.push(GENERATED_HEADER, '');
  // La restricción de compilación va antes de la cláusula package, separada por una línea en blanco: si no, Go la
  // lee como el comentario del paquete y la ignora.
  if (build) parts.push(`//go:build ${build}`, '');
  if (doc) parts.push(...commentLines(doc), `package ${pkg}`);
  else parts.push(`package ${pkg}`);
  const code = body.replace(/^\n+/, '').replace(/\s+$/, '');
  const block = importBlock(used, module);
  if (block) parts.push('', block);
  // Un archivo que solo documenta el paquete (doc.go) acaba en la cláusula package.
  if (code) parts.push('', code);
  parts.push('');
  return parts.join('\n');
}

/** Un comentario de documentación: cada línea con `// `, y las vacías con `//` a secas, como gofmt. */
export function commentLines(text, indent = '') {
  return text
    .trim()
    .split('\n')
    .map((line) => (line.trim() ? `${indent}// ${line.trimEnd()}` : `${indent}//`));
}

function normalize(entry, module) {
  const spec = typeof entry === 'string' ? { path: entry } : { ...entry };
  if (module && spec.path.startsWith('internal/')) spec.path = `${module}/${spec.path}`;
  if (module && (spec.path === 'config' || spec.path.startsWith('config/'))) spec.path = `${module}/${spec.path}`;
  return spec;
}

/** Los imports que el cuerpo usa, sin repetir. Un `_` o un alias se respetan tal cual. */
export function collectImports(imports, body, module = null) {
  const code = stripCommentsAndStrings(body);
  const byPath = new Map();
  for (const entry of imports) {
    const spec = normalize(entry, module);
    if (byPath.has(spec.path)) continue;
    if (spec.name === '_') {
      byPath.set(spec.path, spec);
      continue;
    }
    const name = spec.name ?? packageNameOf(spec.path);
    if (new RegExp(`(^|[^A-Za-z0-9_.])${name}\\.`).test(code)) byPath.set(spec.path, spec);
  }
  return [...byPath.values()];
}

/** El bloque de imports en los tres grupos de goimports, cada uno ordenado por ruta. */
export function importBlock(specs, module = null) {
  if (specs.length === 0) return '';
  const own = (spec) => module && (spec.path === module || spec.path.startsWith(`${module}/`));
  const groups = [specs.filter((s) => !own(s) && isStdlib(s.path)), specs.filter((s) => !own(s) && !isStdlib(s.path)), specs.filter(own)]
    .map((group) => group.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0)))
    .filter((group) => group.length > 0);
  const line = (spec) => `${spec.name ? `${spec.name} ` : ''}"${spec.path}"`;
  if (specs.length === 1) return `import ${line(specs[0])}`;
  return ['import (', groups.map((group) => group.map((spec) => `\t${line(spec)}`).join('\n')).join('\n\n'), ')'].join('\n');
}

/**
 * Quita comentarios, cadenas y runas para que el colector no cuente un `fmt.` dentro de un texto. Conserva
 * la longitud de nada: solo sirve para buscar.
 */
export function stripCommentsAndStrings(code) {
  let out = '';
  let i = 0;
  while (i < code.length) {
    const two = code.slice(i, i + 2);
    if (two === '//') {
      const end = code.indexOf('\n', i);
      i = end < 0 ? code.length : end;
    } else if (two === '/*') {
      const end = code.indexOf('*/', i + 2);
      i = end < 0 ? code.length : end + 2;
    } else if (code[i] === '`') {
      const end = code.indexOf('`', i + 1);
      i = end < 0 ? code.length : end + 1;
      out += '""';
    } else if (code[i] === '"' || code[i] === "'") {
      const quote = code[i];
      i++;
      while (i < code.length && code[i] !== quote && code[i] !== '\n') i += code[i] === '\\' ? 2 : 1;
      i++;
      out += '""';
    } else {
      out += code[i];
      i++;
    }
  }
  return out;
}

// ─── Alineación ──────────────────────────────────────────────────────────────────────────────────

/**
 * Alinea filas de celdas como el tabwriter de gofmt. `rows` es una lista de:
 *   · `{ indent, cells }`: una línea con sus celdas (`['Nombre', 'Tipo', '`json:"x"`']`);
 *   · `{ text }`: una línea literal —un comentario— que CORTA la sección, como en gofmt (medido: un comentario
 *     entre dos campos de un struct hace que no se alineen);
 *   · `null`: una línea en blanco, que también la corta.
 * Dentro de una sección, cada columna salvo la última de su fila se rellena con espacios hasta la celda más
 * ancha de su BLOQUE más uno; un bloque de columna son las filas CONTIGUAS que tienen esa columna sin ser la
 * última (si una fila tiene menos celdas, el bloque se corta ahí, como en el tabwriter).
 *
 * Es la regla de los campos de un struct (`Nombre Tipo Tag`) y de un bloque const/var (`Nombre = valor`).
 */
export function alignRows(rows) {
  const lines = [];
  let section = [];
  const flush = () => {
    const widths = section.map((row) => row.cells.map(() => 0));
    const columns = Math.max(0, ...section.map((row) => row.cells.length - 1));
    for (let column = 0; column < columns; column++) {
      let start = 0;
      while (start < section.length) {
        if (section[start].cells.length - 1 <= column) {
          start++;
          continue;
        }
        let end = start;
        while (end < section.length && section[end].cells.length - 1 > column) end++;
        const width = Math.max(...section.slice(start, end).map((row) => row.cells[column].length));
        for (let i = start; i < end; i++) widths[i][column] = width;
        start = end;
      }
    }
    section.forEach((row, rowIndex) => {
      const cells = row.cells.map((cell, index) => (index < row.cells.length - 1 ? cell.padEnd(widths[rowIndex][index] + 1) : cell));
      lines.push(`${row.indent ?? ''}${cells.join('')}`.trimEnd());
    });
    section = [];
  };
  for (const row of rows) {
    if (row === null) {
      flush();
      lines.push('');
    } else if (row.text !== undefined) {
      flush();
      lines.push(row.text);
    } else section.push(row);
  }
  flush();
  return lines;
}

/**
 * Los campos de un literal compuesto con clave (`Clave: valor,`), alineados como go/printer: los valores se
 * alinean tras la clave mientras las claves sean cortas (≤ 40) o su tamaño no se aleje 2,5 veces de la media
 * geométrica de las anteriores; si se aleja, empieza otra sección. `pairs` es una lista de `[clave, valor]` en
 * una línea cada uno.
 */
export function keyedLiteral(pairs, indent = '\t') {
  const rows = [];
  let log2sum = 0;
  let count = 0;
  let prevSize = 0;
  pairs.forEach(([key, value], index) => {
    const size = key.length;
    if (index > 0 && prevSize > 0 && size > 0) {
      let breaks = true;
      if (count === 0 || (prevSize <= 40 && size <= 40)) breaks = false;
      else {
        const ratio = size / exp2ish(log2sum / count);
        breaks = 2.5 * ratio <= 1 || 2.5 <= ratio;
      }
      if (breaks) {
        rows.push({ break: true });
        log2sum = 0;
        count = 0;
      }
    }
    rows.push({ indent, cells: [`${key}:`, `${value},`] });
    log2sum += log2ish(size);
    count++;
    prevSize = size;
  });
  // Una ruptura de sección de go/printer es un salto de página del tabwriter, no una línea en blanco.
  const lines = [];
  let section = [];
  const flush = () => {
    lines.push(...alignRows(section));
    section = [];
  };
  for (const row of rows) {
    if (row.break) flush();
    else section.push(row);
  }
  flush();
  return lines;
}

// Las aproximaciones de go/printer (math.go): la decisión de alinear depende de ellas, no de log2 exacto.
function log2ish(x) {
  const [f, e] = frexp(x);
  return e + 2 * (f - 1);
}

function exp2ish(x) {
  const n = Math.floor(x);
  return (1 + (x - n)) * 2 ** n;
}

function frexp(x) {
  if (x === 0) return [0, 0];
  const e = Math.floor(Math.log2(Math.abs(x))) + 1;
  return [x / 2 ** e, e];
}

/** Un literal de cadena Go interpretado: escapa barras, comillas y saltos de línea. */
export function goString(value) {
  return JSON.stringify(String(value));
}
