// Conocimiento del generador dentro del proyecto: el archivo de contexto del repo, la skill `keel-generate-go`
// y las docs de apoyo. Junto con el snapshot de specs/, hace el repo autosuficiente.
//
// Dos destinos, igual que en los otros tres generadores:
//   · lo que el harness CARGA —la skill, el archivo de contexto— se PROYECTA a la convención de cada harness
//     soportado (HARNESSES de keel-core);
//   · lo que solo es markdown que un agente lee por ruta —architecture, constitution, conventions— va a
//     `docs/keel/`, UNA sola copia, y no puede citar rutas de harness.
//
// Estado (incremento 2 de PLAN-KEEL-GO.md): todavía no hay pipeline de agentes —llega en el incremento 7, con
// el arnés de integración—, así que la skill dice exactamente eso y lo que sí se puede hacer ya, en vez de
// prometer una generación que no existe. Las reglas de Go del § 3 del plan sí van ya: son contrato de lo que
// escriba cualquiera en el proyecto.

import fs from 'node:fs';
import path from 'node:path';
import { HARNESSES, applyTokens } from '@keel-system/keel-core';
import { describeStack } from '@keel-system/keel-core/gen/stack';
import { assetsDir, SKILL } from '../lib/assets.js';
import { layout } from './render.js';

const generatorDir = path.join(assetsDir, 'generators', 'go');

/** Raíz de las docs de apoyo en el proyecto generado; es también el valor del token {{keel:docs}}. */
export const DOCS_DIR = 'docs/keel';

/** Docs de primer nivel del generador, junto a conventions/ bajo DOCS_DIR. */
export const GUIDES = ['architecture.md', 'constitution.md'];

/** Las convenciones, una por bloque del § 3 del plan: el único punto de instalación. */
export const CONVENTIONS = ['naming.md', 'errors.md', 'context.md', 'concurrency.md', 'http.md', 'testing.md'];

export function generate(model) {
  const files = [];
  for (const name of GUIDES) files.push({ path: `${DOCS_DIR}/${name}`, content: docContent(path.join(generatorDir, name)) });
  for (const name of CONVENTIONS) {
    files.push({ path: `${DOCS_DIR}/conventions/${name}`, content: docContent(path.join(generatorDir, 'conventions', name)) });
  }
  for (const harness of HARNESSES) {
    const tokens = { ...harness.tokens, docs: DOCS_DIR };
    files.push({ path: harness.contextFile, content: applyTokens(contextMd(model), tokens) });
    files.push({ path: harness.skillPath(SKILL, 'SKILL.md'), content: applyTokens(skillMd(model), tokens) });
  }
  return files;
}

// El archivo de contexto de cada harness tiene otro nombre en el otro: en material compartido sería tan mentira
// como una ruta `.claude/`.
const CONTEXT_FILES = new RegExp(`\\b(${HARNESSES.map((h) => h.contextFile.replace('.', '\\.')).join('|')})`, 'g');

/**
 * Las docs viven en un único sitio, compartido por todos los harnesses: solo se resuelve `{{keel:docs}}`, y
 * cualquier token de harness o nombre de archivo de contexto es un error de la fuente.
 */
export function docContent(sourceFile) {
  const resolved = applyTokens(fs.readFileSync(sourceFile, 'utf8'), { docs: DOCS_DIR });
  const leftover = resolved.match(/\{\{keel:\w+\}\}/g);
  if (leftover) {
    throw new Error(`${path.basename(sourceFile)} cita rutas de harness (${[...new Set(leftover)].join(', ')}), pero vive en ${DOCS_DIR}/ y lo leen todos.`);
  }
  const contextFiles = resolved.match(CONTEXT_FILES);
  if (contextFiles) {
    throw new Error(`${path.basename(sourceFile)} nombra el archivo de contexto (${[...new Set(contextFiles)].join(', ')}), que en otro harness se llama de otra forma.`);
  }
  return resolved;
}

function contextMd(model) {
  const { service } = model;
  const pkgs = layout(model);
  const layers = Object.keys(model.layersPresent).filter((layer) => model.layersPresent[layer]);
  return `# ${service.projectName}

Servicio Go generado por \`keel-go build\` desde \`specs/${service.name}\` v${service.version}. Es el equivalente de
los servidores de keel-spring, keel-nest y keel-dotnet del mismo diseño: mismo contrato HTTP, mismo cable, mismo
esquema. Equivalente por fuera, Go por dentro.

- **Diseño**: \`specs/\` es un snapshot del diseño Keel; el canónico vive en el workspace de diseño. No se edita aquí.
- **Capas declaradas**: ${layers.length > 0 ? layers.join(', ') : '(ninguna)'}.
- **Stack** (\`keel-stack.json\`): ${describeStack(model.stack)}.
- **Arquitectura**: hexagonal + CQRS (\`{{keel:docs}}/architecture.md\`), un módulo con un paquete por capa
  (\`${pkgs.domain.dir}\`, \`${pkgs.application.dir}\`, \`${pkgs.httpapi.dir}\`, \`internal/infrastructure/*\`,
  \`internal/platform/*\`). La frontera la ejecuta \`${pkgs.architecture.dir}\`.
- **Reglas inviolables**: \`{{keel:docs}}/constitution.md\`, y las de Go en \`{{keel:docs}}/conventions/\`.
- **Código generado**: un archivo con \`// Code generated by keel-go. DO NOT EDIT.\` lo escribe \`keel-go build\` y no
  se toca a mano; lo que no la lleva es tuyo.
- **Módulos**: solo con licencia permisiva (MIT, Apache-2.0, BSD, ISC); nada GPL, AGPL, BUSL ni SSPL, tampoco
  como herramienta (golangci-lint es GPL-3.0: el lint es \`go vet\` + staticcheck).

## Verificación

\`\`\`bash
go mod tidy                 # la primera vez
go build ./... && go test ./...
go vet ./... && go tool staticcheck ./...
gofmt -l .                  # vacío
go run ./${pkgs.server.dir}       # GET /livez y /readyz → {"status":"UP"}
\`\`\`

## Estado del generador

keel-go se construye por incrementos (PLAN-KEEL-GO.md del repo de Keel). Esta versión genera el módulo que
arranca, su configuración, sus sondas y la prueba de su frontera; el código del dominio, los casos de uso y la
API llega en los incrementos 4 y 5, y el pipeline de agentes de \`/${SKILL}\` en el 7.
`;
}

function skillMd(model) {
  const { service } = model;
  const pkgs = layout(model);
  return `---
name: ${SKILL}
description: Completa la generación de este microservicio Go a partir del diseño Keel incluido en specs/. Usar dentro de este proyecto, sin argumentos.
---

# /${SKILL} — completar ${service.projectName}

Este proyecto lo generó \`keel-go build\` desde \`specs/${service.name}\` v${service.version}.

**Todavía no hay pipeline de completado.** keel-go se construye por incrementos y el orquestador de subagentes
(código, infraestructura, pruebas de integración, validación funcional y calidad) llega en el incremento 7 de
PLAN-KEEL-GO.md, junto con el arnés que puntúa los escenarios \`FL-*\`. No escribas el servidor a mano a partir de
\`specs/\` para suplirlo: sin el arnés no hay forma de saber si es equivalente al que generan keel-spring,
keel-nest y keel-dotnet del mismo diseño, que es el objetivo.

Lo que sí puedes hacer ahora, con el cwd en esta raíz:

1. \`go mod tidy\` — resuelve las dependencias indirectas y escribe \`go.sum\`.
2. \`go test ./...\` — la configuración, las sondas, el arranque y la frontera hexagonal.
3. \`go vet ./... && go tool staticcheck ./... && gofmt -l .\` — sin hallazgos.
4. \`go run ./${pkgs.server.dir}\` — \`GET /livez\` y \`GET /readyz\` responden \`{"status":"UP"}\`.

Si algo de eso falla en un proyecto recién generado, es un defecto de keel-go: repórtalo con la salida.
`;
}
